"""Leaderboard: rank scores and render to json / csv / markdown / branded HTML."""
from __future__ import annotations

import csv as _csv
import io
import json

from .metrics import ModelScore

SITE = "https://modelfights.com"
TAGLINE = "SportsBench — the open benchmark for LLM sports prediction"


def rank(scores: list[ModelScore], by: str = "roi") -> list[ModelScore]:
    """Sort models. Default by ROI; Brier as the tie-break / alt sort key.

    Models with no settled picks sink to the bottom.
    """
    def key(s: ModelScore):
        if by == "brier":
            return (s.brier if s.brier is not None else 9e9,)
        if by == "win_rate":
            return (-(s.win_rate or -1),)
        if by == "clv":
            return (-(s.avg_clv if s.avg_clv is not None else -9e9),)
        return (-(s.roi if s.roi is not None else -9e9),)  # roi
    return sorted([s for s in scores if s.settled], key=key) + \
        [s for s in scores if not s.settled]


def to_json(scores: list[ModelScore]) -> str:
    return json.dumps([s.to_row() for s in scores], indent=2)


def to_csv(scores: list[ModelScore]) -> str:
    buf = io.StringIO()
    cols = ["model", "provider", "settled", "win_rate", "brier", "logloss",
            "roi", "units", "clv", "ece", "errors"]
    w = _csv.DictWriter(buf, fieldnames=cols)
    w.writeheader()
    for s in scores:
        w.writerow(s.to_row())
    return buf.getvalue()


def to_markdown(scores: list[ModelScore], title: str = "SportsBench Leaderboard") -> str:
    head = "| # | Model | Picks | Win% | Brier | ROI% | Units | CLV% | ECE |\n"
    head += "|--:|-------|------:|-----:|------:|-----:|------:|-----:|----:|\n"
    rows = ""
    for i, s in enumerate(scores, 1):
        r = s.to_row()
        rows += (f"| {i} | {r['model']} | {r['settled']} | {_f(r['win_rate'])} | "
                 f"{_f(r['brier'])} | {_f(r['roi'])} | {_f(r['units'])} | "
                 f"{_f(r['clv'])} | {_f(r['ece'])} |\n")
    footer = f"\n> {TAGLINE}. See 45+ models graded live at {SITE}\n"
    return f"## {title}\n\n{head}{rows}{footer}"


def to_html(scores: list[ModelScore], title: str = "SportsBench Leaderboard") -> str:
    body = ""
    for i, s in enumerate(scores, 1):
        r = s.to_row()
        body += (f"<tr><td>{i}</td><td>{r['model']}</td><td>{r['settled']}</td>"
                 f"<td>{_f(r['win_rate'])}</td><td>{_f(r['brier'])}</td>"
                 f"<td>{_f(r['roi'])}</td><td>{_f(r['units'])}</td>"
                 f"<td>{_f(r['clv'])}</td><td>{_f(r['ece'])}</td></tr>")
    return _HTML_TEMPLATE.format(title=title, rows=body, site=SITE, tagline=TAGLINE)


def _f(v) -> str:
    return "—" if v is None else (f"{v}" if not isinstance(v, float) else f"{v:g}")


